-- L0 Core Conformance Tests
-- SLDS L0: create, resolve, update, delete — MUST pass for any SLDS implementation.

local helpers = require("spec.helpers")
local Identity = require("slds.domain.identity")
local Errors = require("slds.domain.errors")

describe("Conformance L0 — Core", function()
    local svc

    before_each(function()
        svc = helpers.fixture()
    end)

    describe("create_basic", function()
        it("creates a short link with generated code", function()
            local link, err = svc:create({}, { target = "https://example.com" })
            assert.is_nil(err)
            assert.is_truthy(link)
            assert.is_truthy(link.code)
            assert.are.equal("https://example.com", link.target)
        end)

        it("generated link can be resolved", function()
            local link = svc:create({}, { target = "https://example.com" })
            local result = svc:resolve({}, Identity.new("default", link.code))
            assert.is_true(result.found)
            assert.are.equal("https://example.com", result.target)
        end)
    end)

    describe("create_with_custom_code", function()
        it("creates with a user-specified code", function()
            local link = svc:create({}, { code = "mycode", target = "https://x.com" })
            assert.are.equal("mycode", link.code)
        end)
    end)

    describe("resolve_active", function()
        it("resolves an active link and returns target", function()
            svc:create({}, { code = "abc", target = "https://example.com" })
            local result = svc:resolve({}, Identity.new("default", "abc"))
            assert.is_true(result.found)
            assert.are.equal("https://example.com", result.target)
            assert.are.equal("ACTIVE", result.status)
        end)

        it("returns ResolutionResult not ShortLink", function()
            svc:create({}, { code = "abc", target = "https://example.com" })
            local result = svc:resolve({}, Identity.new("default", "abc"))
            local Resolution = require("slds.domain.resolution")
            assert.are.equal(getmetatable(result), Resolution)
        end)
    end)

    describe("resolve_not_found", function()
        it("returns found=false for non-existent identity", function()
            local result = svc:resolve({}, Identity.new("default", "nonexistent"))
            assert.is_false(result.found)
            assert.are.equal(Errors.NOT_FOUND, result.status)
            assert.is_nil(result.target)
        end)
    end)

    describe("update_target", function()
        it("updates the target URL", function()
            svc:create({}, { code = "abc", target = "https://old.com" })
            local updated = svc:update({}, Identity.new("default", "abc"), { target = "https://new.com" })
            assert.are.equal("https://new.com", updated.target)
        end)

        it("resolve reflects the updated target", function()
            svc:create({}, { code = "abc", target = "https://old.com" })
            svc:update({}, Identity.new("default", "abc"), { target = "https://new.com" })
            local result = svc:resolve({}, Identity.new("default", "abc"))
            assert.are.equal("https://new.com", result.target)
        end)
    end)

    describe("update_status", function()
        it("updates status ACTIVE → DISABLED", function()
            svc:create({}, { code = "abc", target = "https://x.com" })
            local updated = svc:update({}, Identity.new("default", "abc"), { status = "DISABLED" })
            assert.are.equal("DISABLED", updated.status)
        end)
    end)

    describe("delete_basic", function()
        it("deletes a link and it becomes unresolvable", function()
            svc:create({}, { code = "abc", target = "https://x.com" })
            local ok = svc:delete({}, Identity.new("default", "abc"))
            assert.is_true(ok)
            local result = svc:resolve({}, Identity.new("default", "abc"))
            assert.is_true(result.found)
            assert.are.equal(Errors.DELETED, result.status)
            assert.is_nil(result.target)
        end)
    end)

    describe("code_immutability", function()
        it("update with code change MUST fail", function()
            svc:create({}, { code = "abc", target = "https://x.com" })
            assert.has_error(function()
                svc:update({}, Identity.new("default", "abc"), { code = "newcode" })
            end)
        end)
    end)
end)
