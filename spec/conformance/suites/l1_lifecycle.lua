-- L1 Lifecycle Conformance Tests
-- SLDS L1: expiration, disabled, custom code, deleted code reuse.

local helpers = require("spec.helpers")
local Identity = require("slds.domain.identity")
local Errors = require("slds.domain.errors")

local busted = require("busted")
local describe, it = busted.describe, busted.it
local assert = require("luassert")

return function(make_fixture)
describe("Conformance L1 — Lifecycle", function()
    describe("resolve_disabled", function()
        it("disabled link returns status=DISABLED, not resolvable", function()
            local svc = make_fixture()
            svc:create({}, { code = "abc", target = "https://x.com" })
            svc:update({}, Identity.new("default", "abc"), { status = "DISABLED" })
            local result = svc:resolve({}, Identity.new("default", "abc"))
            assert.is_true(result.found)
            assert.are.equal("DISABLED", result.status)
            assert.is_nil(result.target)
        end)
    end)

    describe("resolve_deleted", function()
        it("deleted link returns status=DELETED, not resolvable", function()
            local svc = make_fixture()
            svc:create({}, { code = "abc", target = "https://x.com" })
            svc:delete({}, Identity.new("default", "abc"))
            local result = svc:resolve({}, Identity.new("default", "abc"))
            assert.is_true(result.found)
            assert.are.equal("DELETED", result.status)
            assert.is_nil(result.target)
        end)
    end)

    describe("resolve_expired", function()
        it("expired link returns status=EXPIRED, not resolvable", function()
            local svc = make_fixture({ clock = helpers.fake_clock(2000) })
            svc:create({}, { code = "exp", target = "https://x.com", expires_at = 1000 })
            local result = svc:resolve({}, Identity.new("default", "exp"))
            assert.is_true(result.found)
            assert.are.equal("EXPIRED", result.status)
            assert.is_nil(result.target)
        end)

        it("non-expired link with expires_at resolves normally", function()
            local svc = make_fixture({ clock = helpers.fake_clock(500) })
            svc:create({}, { code = "exp", target = "https://x.com", expires_at = 1000 })
            local result = svc:resolve({}, Identity.new("default", "exp"))
            assert.is_true(result.found)
            assert.are.equal("ACTIVE", result.status)
            assert.are.equal("https://x.com", result.target)
        end)
    end)

    describe("expiration_not_stored", function()
        it("EXPIRED is derived at resolution time, stored status remains ACTIVE", function()
            local svc = make_fixture({ clock = helpers.fake_clock(500) })
            svc:create({}, { code = "exp", target = "https://x.com", expires_at = 1000 })
            -- At t=500, link is ACTIVE
            local r1 = svc:resolve({}, Identity.new("default", "exp"))
            assert.are.equal("ACTIVE", r1.status)
            -- At t=2000, same link is EXPIRED (derived)
            local svc2 = make_fixture({
                repository = svc.repository,
                clock = helpers.fake_clock(2000),
            })
            local r2 = svc2:resolve({}, Identity.new("default", "exp"))
            assert.are.equal("EXPIRED", r2.status)
        end)
    end)

    describe("re_enable_disabled", function()
        it("DISABLED → ACTIVE transition via update", function()
            local svc = make_fixture()
            svc:create({}, { code = "abc", target = "https://x.com" })
            svc:update({}, Identity.new("default", "abc"), { status = "DISABLED" })
            -- Re-enable
            svc:update({}, Identity.new("default", "abc"), { status = "ACTIVE" })
            local result = svc:resolve({}, Identity.new("default", "abc"))
            assert.are.equal("ACTIVE", result.status)
            assert.are.equal("https://x.com", result.target)
        end)
    end)

    describe("delete_is_terminal", function()
        it("DELETED cannot transition to ACTIVE", function()
            local svc = make_fixture()
            svc:create({}, { code = "abc", target = "https://x.com" })
            svc:delete({}, Identity.new("default", "abc"))
            local value, err = svc:update({}, Identity.new("default", "abc"), { status = "ACTIVE" })
            assert.is_nil(value)
            assert.equal(Errors.INVALID, err)
        end)

        it("DELETED cannot transition to DISABLED", function()
            local svc = make_fixture()
            svc:create({}, { code = "abc", target = "https://x.com" })
            svc:delete({}, Identity.new("default", "abc"))
            local value, err = svc:update({}, Identity.new("default", "abc"), { status = "DISABLED" })
            assert.is_nil(value)
            assert.equal(Errors.INVALID, err)
        end)
    end)

    describe("custom_code_conflict", function()
        it("creating with an existing code MUST fail atomically", function()
            local svc = make_fixture()
            local link1 = svc:create({}, { code = "dup", target = "https://x.com" })
            assert.is_truthy(link1)
            local link2, err = svc:create({}, { code = "dup", target = "https://y.com" })
            assert.is_nil(link2)
            assert.are.equal(Errors.CONFLICT, err)
        end)
    end)

    describe("deleted_code_not_reused", function()
        it("deleted codes MUST NOT be reused by default (RULE-006)", function()
            local svc = make_fixture()
            svc:create({}, { code = "recycled", target = "https://x.com" })
            svc:delete({}, Identity.new("default", "recycled"))
            local link, err = svc:create({}, { code = "recycled", target = "https://y.com" })
            assert.is_nil(link)
            assert.are.equal(Errors.CONFLICT, err)
        end)
    end)
end)
end
