local Identity = require("slds.domain.identity")

describe("Identity", function()
    describe("DEFAULT_NAMESPACE", function()
        it("exports the default namespace constant", function()
            assert.are.equal("default", Identity.DEFAULT_NAMESPACE)
        end)
    end)

    describe("new()", function()
        it("creates with namespace and code", function()
            local id = Identity.new("default", "a8Kx2")
            assert.are.equal("default", id.namespace)
            assert.are.equal("a8Kx2", id.code)
        end)

        it("defaults namespace to 'default' with single arg", function()
            local id = Identity.new("a8Kx2")
            assert.are.equal("default", id.namespace)
            assert.are.equal("a8Kx2", id.code)
        end)

        it("rejects empty namespace", function()
            assert.has_error(function()
                Identity.new("", "abc")
            end)
        end)

        it("rejects empty code", function()
            assert.has_error(function()
                Identity.new("default", "")
            end)
        end)

        it("rejects non-string namespace", function()
            assert.has_error(function()
                Identity.new(nil, "abc")
            end)
        end)

        it("rejects non-string code", function()
            assert.has_error(function()
                Identity.new("default", 123)
            end)
        end)
    end)

    describe("equality (__eq)", function()
        it("returns true for same namespace and code", function()
            local a = Identity.new("ns", "abc")
            local b = Identity.new("ns", "abc")
            assert.is_true(a == b)
        end)

        it("returns false for different namespace", function()
            local a = Identity.new("ns1", "abc")
            local b = Identity.new("ns2", "abc")
            assert.is_false(a == b)
        end)

        it("returns false for different code", function()
            local a = Identity.new("ns", "abc")
            local b = Identity.new("ns", "xyz")
            assert.is_false(a == b)
        end)
    end)

    describe("__tostring", function()
        it("formats as namespace:code", function()
            local id = Identity.new("default", "abc")
            assert.are.equal("default:abc", tostring(id))
        end)
    end)
end)
